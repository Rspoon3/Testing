import Foundation
@testable import TestDrive

/// Raw characteristic values captured from a real STEPR stair climber
/// (`WLT5283M_CA32`, LiXuan `E-masX`, firmware V1.1), together with the readings
/// photographed off the machine's own console at the same moment.
///
/// These are the ground truth the decoders are checked against. Nothing here is
/// synthesised — where a test needs a payload the machine never produced, it says so.
enum CapturedPackets {

    // MARK: - Stair Climber Data (0x2AD0)

    /// Session 1, final packet. Console: STEPS 96, FLOORS 4, CALORIES 16,
    /// TIME 1:28, ALTITUDE 38 ft, SPEED 0, PULSE 0.
    static let session1Final = Data([
        0xFE, 0x03, 0xF9, 0x10, 0x00, 0x00, 0x00, 0x00, 0x0B, 0x00, 0x60, 0x00,
        0x10, 0x00, 0xFF, 0xFF, 0xFF, 0x00, 0x00, 0x58, 0x00, 0x00, 0x00
    ])

    /// Session 1, mid-workout at the highest speed reached that session (16).
    static let session1AtPeakSpeed = Data([
        0xFE, 0x03, 0xFA, 0x10, 0x10, 0x00, 0x00, 0x00, 0x07, 0x00, 0x3F, 0x00,
        0x0A, 0x00, 0xFF, 0xFF, 0xFF, 0x00, 0x00, 0x41, 0x00, 0x00, 0x00
    ])

    /// Session 3, first packet, still carrying session 2's totals before the machine
    /// reset itself. Console at the end of session 2: STEPS 48, FLOORS 2, CALORIES 8.
    static let session3CarriedOver = Data([
        0xFE, 0x03, 0xFB, 0x10, 0x00, 0x00, 0x00, 0x00, 0x05, 0x00, 0x30, 0x00,
        0x08, 0x00, 0xFF, 0xFF, 0xFF, 0x00, 0x00, 0x39, 0x00, 0x00, 0x00
    ])

    /// Session 3, immediately after the machine reset its totals. Every cumulative
    /// field is zero and the floor counter is back at its base of 253.
    static let session3AfterReset = Data([
        0xFE, 0x03, 0xFD, 0x10, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0xFF, 0xFF, 0xFF, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00
    ])

    /// Session 3, three seconds in: one step taken, speed level 7, no floors yet.
    static let session3EarlyClimb = Data([
        0xFE, 0x03, 0xFD, 0x10, 0x07, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00,
        0x00, 0x00, 0xFF, 0xFF, 0xFF, 0x00, 0x00, 0x03, 0x00, 0x00, 0x00
    ])

    /// Session 3, final packet. 126 steps, 6 floors, 21 kcal, 15 m gained, 130 s.
    static let session3Final = Data([
        0xFE, 0x03, 0xF7, 0x10, 0x00, 0x00, 0x00, 0x00, 0x0F, 0x00, 0x7E, 0x00,
        0x15, 0x00, 0xFF, 0xFF, 0xFF, 0x00, 0x00, 0x82, 0x00, 0x00, 0x00
    ])

    /// The all-zero packet the machine emits when idle, before any session begins.
    /// Note the floor slot is `0x0000` here rather than the `0x10FD` base.
    static let idle = Data([
        0xFE, 0x03, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0xFF, 0xFF, 0xFF, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00
    ])

    // MARK: - Other Characteristics

    /// Fitness Machine Feature (0x2ACC).
    static let fitnessMachineFeature = Data([0x50, 0x3F, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00])

    /// Training Status (0x2AD3): idle, no status string.
    static let trainingStatusIdle = Data([0x00, 0x01])

    /// Fitness Machine Status (0x2ADA): the user pressed start.
    static let fitnessMachineStatusStarted = Data([0x04])

    /// Supported Speed Range (0x2AD4). This machine reports no speed range.
    static let supportedSpeedRange = Data([0x00, 0x00, 0x00, 0x00, 0x01, 0x00])

    /// Supported Inclination Range (0x2AD5). Entirely zero.
    static let supportedInclinationRange = Data([0x00, 0x00, 0x00, 0x00, 0x00, 0x00])

    /// Supported Resistance Level Range (0x2AD6): integer levels 1–25, matching the
    /// console's SPEED buttons.
    static let supportedResistanceLevelRange = Data([0x01, 0x00, 0x19, 0x00, 0x01, 0x00])

    /// Supported Power Range (0x2AD8). This machine reports no power range.
    static let supportedPowerRange = Data([0x00, 0x00, 0x00, 0x00, 0x01, 0x00])

    /// Supported Heart Rate Range (0x2AD7). The firmware sends 200 then 50, i.e. the
    /// maximum before the minimum.
    static let supportedHeartRateRange = Data([0xC8, 0x32, 0x01])

    /// Manufacturer Name (0x2A29).
    static let manufacturerName = Data([0x4C, 0x69, 0x58, 0x75, 0x61, 0x6E])

    /// Model Number (0x2A24).
    static let modelNumber = Data([0x45, 0x2D, 0x6D, 0x61, 0x73, 0x58])

    /// Firmware Revision (0x2A26).
    static let firmwareRevision = Data([0x56, 0x31, 0x2E, 0x31])
}
